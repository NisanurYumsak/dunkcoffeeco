class MenuItem {
  final String name;
  final String description;
  final String ingredients;
  final String allergens;
  final String price;
  final String category;
  final String badge;
  final String image;

  const MenuItem({
    required this.name,
    required this.description,
    required this.ingredients,
    required this.allergens,
    required this.price,
    required this.category,
    required this.badge,
    required this.image,
  });
}